// n8n Code node: "Build poster"   (Mode: Run Once for All Items)
// Fills the poster template with the shop's details, the owner's REAL photo and the Copywriter's text, in one of five themes:
//   festive · modern · bold · fresh · elegant. The Strategist picks the theme; a "Change" request can override it
//   (Parse Memory JSON -> design_theme), and the shop's style notes can pin a preferred theme.
// Then an HTTP Request "Render poster": POST https://hcti.io/v1/image, Basic Auth (User ID / API Key),
//   JSON body {{ JSON.stringify($json.hcti) }}, On Error = Continue (regular output) so a failed render falls back to the photo.
// GENERATED by tools/gen_poster_js.py from templates/poster.html + tools/build_poster_body.js. Don't hand-edit.

const TEMPLATE = __TEMPLATE__;
const THEMES = ['festive', 'modern', 'bold', 'fresh', 'elegant'];

const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const okColor = (c, d) => /^#[0-9a-fA-F]{6}$/.test(String(c || '')) ? c : d;
const noEmoji = s => String(s ?? '').replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/gu, '').trim();

const d = $('Decide next step').first().json;
const shop = d.shop || {};
const copy = $('Parse Copywriter JSON').first().json;
let strat = {};
try { strat = $('Parse Strategist JSON').first().json; }
catch (e) { try { strat = JSON.parse($('Get post').first().json.strategy_json || '{}'); } catch (e2) {} }
let override = null;
try { const m = $('Parse Memory JSON').first().json; if (m.ok && THEMES.includes(m.design_theme)) override = m.design_theme; } catch (e) {}
const theme = override || (THEMES.includes(strat.design_theme) ? strat.design_theme : 'modern');

let photo = '';
try { const p = $('Photo to base64').first().json; photo = `data:${p.photo_mime};base64,${p.photo_b64}`; }
catch (e) { photo = 'data:image/svg+xml;utf8,' + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="900" height="560"><rect width="100%" height="100%" fill="#d9d6cf"/></svg>'); }

const priceText = noEmoji(copy.price_text);
const showPrice = strat.show_price !== false && !!priceText;
const priceHtml = (() => { const i = priceText.indexOf('/'); return i > 0 ? `${esc(priceText.slice(0, i))}<small>${esc(priceText.slice(i))}</small>` : esc(priceText); })();
const badge = noEmoji(copy.badge_bn || strat.badge_text_bn || '');
const nameBn = shop.shop_name_bn || shop.shop_name_en || '';
const nameEn = shop.shop_name_en && shop.shop_name_en !== nameBn ? shop.shop_name_en : '';
const phone = shop.phone && !/REPLACE/.test(shop.phone) ? shop.phone : '';
const callWord = shop.languages === 'bn' ? 'ফোন / WhatsApp ' : 'Call / WhatsApp ';

const values = {
  THEME: theme,
  BRAND: okColor(shop.brand_color, '#8B1E3F'), ACCENT: okColor(shop.accent_color, '#F2A93B'),
  SHOP_BN: esc(nameBn), SHOP_EN: esc(nameEn), PHOTO: photo,
  BADGE: esc(badge), BADGE_DISPLAY: badge ? 'block' : 'none',
  HEADLINE: esc(noEmoji(copy.headline_bn)), SUBLINE: esc(noEmoji(copy.subline_bn)),
  PRICE: priceHtml, PRICE_DISPLAY: showPrice ? (theme === 'festive' || theme === 'fresh' ? 'flex' : 'block') : 'none',
  FOOTER_LEFT: esc(shop.area || ''), FOOTER_RIGHT: esc(phone ? callWord + phone : ''),
};
const html = TEMPLATE.replace(/\{\{(\w+)\}\}/g, (m, k) => (k in values ? values[k] : m));

return [{ json: { theme, html_kb: Math.round(html.length / 1024),
  hcti: { html, google_fonts: 'Hind Siliguri|Poppins|Oswald|Playfair Display', viewport_width: 1080, viewport_height: 1080, device_scale: 1, ms_delay: 600 } } }];
